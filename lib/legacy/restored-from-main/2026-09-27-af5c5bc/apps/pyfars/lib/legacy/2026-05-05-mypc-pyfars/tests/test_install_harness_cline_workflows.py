def test_helper_script_appends_witness_when_executed(tmp_path, monkeypatch):
    """Smoke: the generated helper, when invoked with positional args,
    actually constructs and appends a bilattice-valued Witness with
    the right channel, origin, and bilattice axes. This is the proof
    the projection's contract holds end-to-end."""
    _write_runbook(tmp_path, "alpha", step_count=2)
    _write_profile(tmp_path)
    target = tmp_path / ".clinerules"
    # Mirror the real-repo layout; the helper itself resolves PyFARS
    # through the Nix-provided `pyfars` command on PATH.
    real_fars = Path(__file__).parent.parent  # operations/engineering/pyfars
    fars_dest = tmp_path / "operations/engineering/pyfars"
    fars_dest.parent.mkdir(parents=True, exist_ok=True)
    fars_dest.symlink_to(real_fars, target_is_directory=True)
    _install_cline_workflows(
        root=tmp_path, target=target, prefix="pyfars-", dry_run=False)
    helper = tmp_path / ".fars/cline-witness.sh"
    env = os.environ.copy()
    env["FARS_ROOT"] = str(tmp_path)
    result = subprocess.run(
        ["bash", str(helper), "alpha", "step-1", "0.5", "0.5"],
        env=env, capture_output=True, text=True, check=False, cwd=str(tmp_path),
    )
    assert result.returncode == 0, (
        f"helper exited {result.returncode}\nstdout: {result.stdout}\n"
        f"stderr: {result.stderr}"
    )
    # Find the appended witness on the event log.
    log_dir = tmp_path / ".fars/event-log"
    log_files = list(log_dir.glob("*.jsonl"))
    assert len(log_files) == 1
    line = log_files[0].read_text(encoding="utf-8").strip().splitlines()[-1]
    record = json.loads(line)
    assert record["channel"] == "dispatch"
    assert record["origin"] == "cline-workflow:alpha"
    assert record["operator"] == "cline_runbook_step:alpha"
    assert record["target"] == "cline-workflow:alpha"
    assert record["truth"] == 0.5
    assert record["evidence"] == 0.5
    assert record["details"] == {"step": "step-1", "runbook": "alpha"}


def test_walk_accepts_step_heading_variants(tmp_path):
    """Tolerate `### N)`, `### N .`, and up-to-3-space indentation —
    the variants are unusual but valid markdown; rejecting them would
    surprise authors and break legitimate runbook prose."""
    rdir = tmp_path / "operations/engineering/runbooks"
    rdir.mkdir(parents=True)
    (rdir / "variants.md").write_text(
        "---\nkind: runbook\ntitle: variants\n---\n"
        "# variants\n\n## Steps\n\n"
        "### 1) paren style\n\nx\n\n"
        "### 2 . spaced dot\n\ny\n\n"
        "   ### 3. three-space-indented\n\nz\n",
        encoding="utf-8",
    )
    [r] = _walk_runbook_records(tmp_path)
    assert r["step-count"] == 3
    assert [n for n, _ in r["steps"]] == [1, 2, 3]


def test_workflow_text_handles_thematic_break_in_body(tmp_path):
    """A runbook body that itself contains `\\n---\\n` (a markdown
    thematic break) must not confuse the frontmatter stripper. The
    fix uses the parse_fm-cached body, which closes only at the
    first delimiter — so any later `---` survives intact."""
    rdir = tmp_path / "operations/engineering/runbooks"
    rdir.mkdir(parents=True)
    (rdir / "themed.md").write_text(
        "---\nkind: runbook\ntitle: themed\n---\n"
        "# themed\n\n## Steps\n\n### 1. first\n\nA paragraph.\n\n"
        "---\n\n### 2. after the break\n\nAnother paragraph.\n",
        encoding="utf-8",
    )
    [r] = _walk_runbook_records(tmp_path)
    assert r["step-count"] == 2
    text = _cline_workflow_text(root=tmp_path, runbook=r)
    # The mid-body thematic break is preserved.
    assert "\n---\n\n### 2. after the break\n" in text
    # And the frontmatter is gone (no `kind: runbook` line leaked).
    assert "kind: runbook" not in text


def test_uninstall_refuses_path_traversal_in_manifest(tmp_path, capsys):
    """If a tampered manifest points at a path outside the repo root,
    uninstall must skip it (with a warning), not silently delete files
    elsewhere on the filesystem. Same containment guarantee as the
    sister claude-code-hooks uninstaller."""
    _write_runbook(tmp_path, "alpha")
    target = tmp_path / ".clinerules"
    _, manifest_path, _ = _install_cline_workflows(
        root=tmp_path, target=target, prefix="pyfars-", dry_run=False)
    # Plant a "victim" file outside root and tamper the manifest to
    # point at it via `..` traversal.
    outside = tmp_path.parent / "victim.md"
    outside.write_text("do not delete me", encoding="utf-8")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["workflows"].append({
        "slug": "evil",
        "title": "evil",
        "step-count": 1,
        "requires-captain-confirmation": False,
        "out-path": f"../{outside.name}",
        "source-path": "fake",
        "bytes": 0,
    })
    manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
    _uninstall_cline_workflows(
        root=tmp_path, target=target, dry_run=False)
    assert outside.is_file(), "uninstall traversed `..` and deleted outside file!"
    err = capsys.readouterr().err
    assert "refusing to remove" in err
    outside.unlink()


def test_helper_script_uses_pwd_when_fars_root_unset(tmp_path):
    """The helper falls back to `$(pwd)` when FARS_ROOT is unset.
    Verify that path resolution actually works under that fallback,
    not only when the test explicitly sets FARS_ROOT (which would mask
    a `cwd != root` regression in real-repo usage)."""
    _write_runbook(tmp_path, "alpha")
    _write_profile(tmp_path)
    target = tmp_path / ".clinerules"
    real_fars = Path(__file__).parent.parent
    fars_dest = tmp_path / "operations/engineering/pyfars"
    fars_dest.parent.mkdir(parents=True, exist_ok=True)
    fars_dest.symlink_to(real_fars, target_is_directory=True)
    _install_cline_workflows(
        root=tmp_path, target=target, prefix="pyfars-", dry_run=False)
    helper = tmp_path / ".fars/cline-witness.sh"
    env = {k: v for k, v in os.environ.items() if k != "FARS_ROOT"}
    # Pass non-default truth/evidence so the Witness serializer keeps
    # them on the wire (it omits fields that equal the default 1.0).
    result = subprocess.run(
        ["bash", str(helper), "alpha", "step-1", "0.75", "0.25"],
        env=env, capture_output=True, text=True, check=False, cwd=str(tmp_path),
    )
    assert result.returncode == 0, (
        f"pwd-fallback failed: stdout={result.stdout!r} "
        f"stderr={result.stderr!r}"
    )
    log_files = list((tmp_path / ".fars/event-log").glob("*.jsonl"))
    assert len(log_files) == 1
    record = json.loads(
        log_files[0].read_text(encoding="utf-8").strip().splitlines()[-1])
    assert record["truth"] == 0.75
    assert record["evidence"] == 0.25
    assert record["origin"] == "cline-workflow:alpha"


