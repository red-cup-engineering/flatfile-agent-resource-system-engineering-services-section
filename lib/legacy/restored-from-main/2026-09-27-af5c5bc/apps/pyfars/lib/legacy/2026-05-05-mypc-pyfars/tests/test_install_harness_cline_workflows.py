"""Tests for the ``cline-workflows`` PyFARS harness installer.

Covers: walk-and-validate (good runbook, no-numbered-steps rejected,
non-runbook kinds skipped, _index.md skipped), end-to-end install
(workflows directory + helper script written, helper executable,
per-step witness preamble present, frontmatter stripped, captain-
confirmation surfaced), manifest exact, uninstall round-trip
(workflows + helper gone, manifest gone, empty workflows/ removed),
and that the generated witness helper actually appends a bilattice-
valued dispatch witness when invoked.
"""
from __future__ import annotations

import json
import os
