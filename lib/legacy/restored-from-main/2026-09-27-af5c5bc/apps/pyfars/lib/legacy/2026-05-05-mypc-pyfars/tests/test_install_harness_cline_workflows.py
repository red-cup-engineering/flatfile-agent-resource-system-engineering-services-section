def test_install_writes_workflows_helper_and_manifest(tmp_path):
    _write_runbook(tmp_path, "alpha", step_count=2)
    _write_runbook(tmp_path, "beta", step_count=3, confirm=True)
    target = tmp_path / ".clinerules"
    count, manifest_path, entries = _install_cline_workflows(
        root=tmp_path, target=target, prefix="pyfars-", dry_run=False,
    )
    assert count == 2
    assert manifest_path is not None and manifest_path.is_file()
    # Workflow files written.
    for slug in ("alpha", "beta"):
        wf = target / "workflows" / f"{slug}.md"
        assert wf.is_file()
        text = wf.read_text(encoding="utf-8")
        # No leading frontmatter — cline expects markdown body.
        assert not text.startswith("---\n")
        # Banner + per-step witness preamble present.
        assert "Generated by PyFARS `cline-workflows` harness" in text
        assert "Per-step witness protocol" in text
        assert f"bash .fars/cline-witness.sh {slug} step-<N>" in text
        # The runbook prose body survived (Goal section).
        assert "## Goal" in text
        assert "## Steps" in text
    # Captain-confirmation surfaced for beta only.
    beta = (target / "workflows" / "beta.md").read_text(encoding="utf-8")
    alpha = (target / "workflows" / "alpha.md").read_text(encoding="utf-8")
    assert "Captain confirmation required" in beta
    assert "Captain confirmation required" not in alpha
    # Helper script written and executable.
    helper = tmp_path / ".fars/cline-witness.sh"
    assert helper.is_file()
    assert helper.stat().st_mode & stat.S_IXUSR
    helper_text = helper.read_text(encoding="utf-8")
    assert helper_text.startswith("#!/usr/bin/env bash\n")
    # The helper routes through the installed CLI so witness construction
    # stays behind the same runtime boundary as production use.
    assert "exec pyfars witness" in helper_text
    # Manifest shape.
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    assert manifest["harness"] == "cline-workflows"
    assert manifest["context-summary"]["workflow-count"] == 2
    assert manifest["context-summary"]["total-steps"] == 5
    by_slug = {e["slug"]: e for e in manifest["workflows"]}
    assert by_slug["alpha"]["step-count"] == 2
    assert by_slug["beta"]["step-count"] == 3
    assert by_slug["beta"]["requires-captain-confirmation"] is True
    assert by_slug["alpha"]["requires-captain-confirmation"] is False


